const PLACEHOLDER = /\{(\w+)(?:\|([^|}]*)\|([^}]*))?\}/gu

/** Fill {name} and {name|one|many} from vars; a placeholder without a value stays as it is. */
export function fill(text, vars) {
  return text.replace(PLACEHOLDER, (all, name, one, many) => {
    if (!(name in vars)) return all
    const value = String(vars[name])
    return one === undefined ? value : `${value} ${value === '1' ? one : many}`
  })
}

export function t(lang, key, vars) {
  const text = TEXT[lang]?.[key] ?? TEXT.zh[key] ?? key
  return vars ? fill(text, vars) : text
}

export const langOf = locale => (String(locale ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en')
